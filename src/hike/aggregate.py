class UuidAggregate(Aggregate[UUID]):
    """Aggregate with a UUID primary key, auto-generated by default."""

    id: Field[EntityID[UUID]] = field(default_factory=lambda: EntityID(uuid4()))


def authority[**P, R](method: Callable[P, R]) -> Callable[P, R]:
    """Mark a method as an authority check for a cross-aggregate invariant.

    The decorated aggregate is loaded first by the ``DomainService``; its
    return value gates whether the other aggregate(s) may proceed.

    Example::

        class Tenant(UuidAggregate):
            @authority
            def can_add_member(self) -> bool:
                return self.member_count.value < self.plan.max_members.value
    """
    setattr(method, "_is_authority_check", True)
    return method
